package rocks.pkb.plektra.dictionaries

import java.io.File
import java.util.Locale
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.runBlocking
import kotlinx.coroutines.withContext
import kotlinx.serialization.decodeFromString
import kotlinx.serialization.json.Json
import org.junit.Assert.*
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment
import org.robolectric.annotation.Config
import rocks.pkb.plektra.core.suggestions.AndroidDictionaryRepository
import rocks.pkb.plektra.core.suggestions.DictionaryIndex
import rocks.pkb.plektra.core.suggestions.SuggestionEngine
import rocks.pkb.plektra.core.suggestions.UserDictionaryStore

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [33])
class RomanianDictionaryImportTest {
    @Test fun convertedFixtureImportsAndSuggestsRomanianWords() = runBlocking {
        val context = RuntimeEnvironment.getApplication()
        val bytes = checkNotNull(javaClass.getResourceAsStream("/dictionaries/ro_base.dict")).use { it.readBytes() }
        val expected = mapOf("scoala" to ("școală" to 255), "tara" to ("țară" to 195),
            "paine" to ("pâine" to 135), "inger" to ("înger" to 75))
        // This file is generated by the exact CLI commands in the import guide.
        val decoded = Json.decodeFromString<DictionaryIndex>(bytes.decodeToString())
        assertEquals(expected.keys, decoded.normalizedIndex.keys)
        assertEquals(expected.keys, StreamingDictionaryValidator.validate(bytes.inputStream(), expected.keys))
        val target = File(context.filesDir, "dictionaries_serialized/custom/ro_base.dict")
        target.parentFile!!.mkdirs()
        try {
            withContext(Dispatchers.IO) {
                DictionaryFileInstaller.install(bytes.inputStream(), target, emptySet())
            }
            assertArrayEquals(bytes, target.readBytes())
            val locale = Locale.forLanguageTag("ro")
            assertTrue(AndroidDictionaryRepository.hasDictionaryForLocale(context, locale))
            val repository = AndroidDictionaryRepository(context, context.assets, UserDictionaryStore(), locale)
            withContext(Dispatchers.IO) { repository.loadIfNeeded() }
            assertTrue(repository.isReady)
            val engine = SuggestionEngine(repository, locale)
            for ((key, value) in expected) {
                val (word, frequency) = value
                assertEquals(frequency, repository.getExactWordFrequency(word))
                assertTrue(word, repository.lookupByPrefixMerged(key.take(3), 5).any { it.word == word })
                assertTrue("Expected $word after import", engine.suggest(key, includeAccentMatching = true)
                    .any { it.candidate == word })
            }
        } finally { target.delete() }
    }
}
